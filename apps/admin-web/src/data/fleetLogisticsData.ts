export const calculateFleetKpis = (
  trips: TripManifest[],
  vehicles: DeliveryVehicle[]
): FleetKpis => {
  const activeOnRoad = vehicles.filter((v) => v.status === 'in_transit').length;
  const underMaintenance = vehicles.filter((v) => v.status === 'under_maintenance').length;

  const inTransitTrips = trips.filter((t) => t.status === 'dispatched_in_transit').length;
  const completedTrips = trips.filter((t) => t.status === 'completed_delivered' || t.status === 'reconciled_closed').length;

  const totalCodExpected = trips.reduce((sum, t) => sum + t.expectedTotalCod, 0);
  const totalCodCollected = trips.reduce((sum, t) => sum + t.collectedTotalCod, 0);

  const avgPayload = trips.length > 0
    ? Math.round(trips.reduce((sum, t) => sum + t.payloadUtilizationPercent, 0) / trips.length)
    : 0;

  return {
    totalVehiclesCount: vehicles.length,
    activeVehiclesOnRoad: activeOnRoad,
    vehiclesUnderMaintenance: underMaintenance,
    totalTripsToday: trips.length,
    inTransitTripsCount: inTransitTrips,
    completedTripsCount: completedTrips,
    overallOnTimeDeliveryRate: 96.5,
    totalCodExpectedToday: totalCodExpected,
    totalCodCollectedToday: totalCodCollected,
    averagePayloadUtilizationPercent: avgPayload,
  };
};
