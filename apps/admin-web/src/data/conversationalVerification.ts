export interface VerificationKpis {
  totalPendingOrders: number;
  totalPendingValue: number;
  whatsappConfirmedCount: number;
  whatsappAutoConfirmRate: number;
  teleSalesQueueCount: number;
  slaBreachedCount: number;
  averageVerificationMinutes: number;
  stage1Count: number;
  stage2Count: number;
  stage3Count: number;
  stage4Count: number;
  stage5Count: number;
  readyForPickingCount: number;
  releasedForPickingCount: number;
}

export const calculateVerificationKpis = (
  records: ConversationalVerificationRecord[]
): VerificationKpis => {
  const total = records.length;
  const pending = records.filter(
    (r) =>
      r.verificationStatus === 'whatsapp_pending' ||
      r.verificationStatus === 'whatsapp_delivered' ||
      r.verificationStatus === 'whatsapp_read' ||
      r.verificationStatus === 'escalated_telesales' ||
      r.verificationStatus === 'changes_requested'
  );
  const pendingValue = pending.reduce((sum, r) => sum + r.totalAmount, 0);
  const confirmedWhatsapp = records.filter((r) => r.verificationStatus === 'whatsapp_confirmed').length;
  const teleSalesQueue = records.filter(
    (r) =>
      r.verificationStatus === 'escalated_telesales' ||
      r.verificationStatus === 'changes_requested' ||
      r.isSlaBreached
  ).length;
  const slaBreached = records.filter((r) => r.isSlaBreached).length;

  const stage1Count = records.filter((r) => r.currentStage === 1).length;
  const stage2Count = records.filter((r) => r.currentStage === 2).length;
  const stage3Count = records.filter((r) => r.currentStage === 3).length;
  const stage4Count = records.filter((r) => r.currentStage === 4).length;
  const stage5Count = records.filter((r) => r.currentStage === 5).length;

  const readyForPickingCount = records.filter(
    (r) => r.currentStage === 4 || r.verificationStatus === 'whatsapp_confirmed' || r.verificationStatus === 'voice_verified'
  ).length;

  const releasedForPickingCount = records.filter(
    (r) => r.verificationStatus === 'released_for_picking' || r.verificationStatus === 'picked'
  ).length;

  return {
    totalPendingOrders: pending.length,
    totalPendingValue: pendingValue,
    whatsappConfirmedCount: confirmedWhatsapp,
    whatsappAutoConfirmRate: total > 0 ? Math.round((confirmedWhatsapp / total) * 100) : 0,
    teleSalesQueueCount: teleSalesQueue,
    slaBreachedCount: slaBreached,
    averageVerificationMinutes: 12.8,
    stage1Count,
    stage2Count,
    stage3Count,
    stage4Count,
    stage5Count,
    readyForPickingCount,
    releasedForPickingCount,
  };
};
