// Calculation helper for aging buckets
export function calculateAgingBucket(dueDate: string, asOfDate: string = '2026-09-17'): { daysOverdue: number; bucket: AgingBucket } {
  const due = new Date(dueDate);
  const current = new Date(asOfDate);
  const diffTime = current.getTime() - due.getTime();
  const days = Math.floor(diffTime / (1000 * 60 * 60 * 24));

  if (days <= 0) return { daysOverdue: 0, bucket: 'current' };
  if (days <= 30) return { daysOverdue: days, bucket: '1_30' };
  if (days <= 60) return { daysOverdue: days, bucket: '31_60' };
  if (days <= 90) return { daysOverdue: days, bucket: '61_90' };
  return { daysOverdue: days, bucket: 'over_90' };
}
